"""Revision 2: results/revision2/SUMMARY.md from results/revision2/report.json (every number comes from that file).

    python scripts/rev2_summary.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R2 = ROOT / "results" / "revision2"
LAB = {"guided": "Proposed (guided restarts)", "random_prior": "random-prior restarts", "plain": "plain restarts",
       "ours_bok_ls": "Proposed (best-of-k) + LS", "ours_greedy_ls": "Proposed + RR + LS",
       "greedy_ls": "Greedy + RR + LS", "lp_ls": "LP rounding+RR+LS", "cpsat": "CP-SAT"}


def p(x):
    return "n/a" if x != x else ("<1e-4" if x < 1e-4 else f"{x:.4f}")


def g(s):
    return f"{s['gap']:.3f} [{s['lo']:.3f}, {s['hi']:.3f}] ({s['found']}/{s['total']})" if s["found"] else \
        f"-- (0/{s['total']})"


def main():
    r = json.loads((R2 / "report.json").read_text())
    L = ["# Revision 2: GNN-guided restarts and large-n equal-time study", "",
         "All numbers below are generated by `scripts/rev2_summary.py` from `results/revision2/report.json`, which "
         "`scripts/rev2_report.py` computes from the verified traces `results/revision2/step{1,2}_traces.csv` "
         "(produced by `scripts/rev2_run.py`). Tuning: `scripts/rev2_tune.py` -> `checkpoints/guided_restarts.json`. "
         "Decisions: docs/decisions.md R12-R26.", "",
         "Gap = 100 (W - ref) / ref in %, mean over instances, [95% bootstrap CI], (instances with a set / total). "
         "W/T/L = win/tie/loss of guided restarts (instances; no set by the budget = loss).", ""]
    t = r["tuned"]
    L += ["## Tuned parameters (validation only, 48 graphs, objective = mean gap at 1 s)", ""]
    for k in ("ours_guided_restarts", "random_prior_restarts", "plain_restarts"):
        v = t[k]
        L.append(f"- {k}: beta {v['beta']}, tau {v['tau']}, refresh {v['refresh']} -> val gap {v['val_mean_gap_1s']:.3f}% "
                 f"at 1 s ({v['val_mean_gap_016s']:.3f}% at 0.16 s)")
    if "step1" in r:
        s1 = r["step1"]
        L += ["", f"## Step 1: n = 100, 200 ({s1['instances']} instances with proven optima; "
              f"{s1['unproven_excluded']} unproven excluded)", "", "### Mean gap to the proven optimum (%)", "",
              "| method | budget | pooled | degree | inverse | random | mixed |", "|---|---|---|---|---|---|---|"]
        for m in LAB:
            for b in ("0.16", "1.0", "5.0"):
                k = f"{m}@{b}"
                if k in s1:
                    L.append(f"| {LAB[m]} | {b} s | " + " | ".join(g(s1[k][x]) for x in
                                                                  ("pooled", "degree", "inverse", "random", "mixed")) + " |")
        L += ["", "### Paired tests: guided restarts vs X (Wilcoxon p; W/T/L; mean dW = W(guided) - W(X))", "",
              "| X | budget | scope | p | W/T/L | mean dW |", "|---|---|---|---|---|---|"]
        for c in ("random_prior", "plain", "lp_ls", "cpsat", "ours_bok_ls"):
            for b in ("0.16", "1.0", "5.0"):
                k = f"guided_vs_{c}@{b}"
                if k not in s1:
                    continue
                for sc in ("pooled", "degree", "inverse", "random", "mixed"):
                    x = s1[k][sc]
                    L.append(f"| {LAB[c]} | {b} s | {sc} | {p(x['p'])} | {x['win']}/{x['tie']}/{x['loss']} | "
                             f"{x['mean_diff']:+.3f} |")
        if "guided_seed1_half" in s1:
            L += ["", "### Guided restarts with the seed-1 checkpoint (every second instance)", ""]
            for b, x in s1["guided_seed1_half"].items():
                L.append(f"- {b} s: seed 1 gap {x['gap_seed1']:.3f}% vs seed 0 {x['gap_seed0_same']:.3f}% on the same "
                         f"{x['n']} instances; Wilcoxon p {p(x['p'])}; seed-1 W/T/L {x['wtl']}")
    if "step2" in r:
        s2 = r["step2"]
        L += ["", f"## Step 2: large n ({s2['instances']} instances; no proven optima)", "",
              f"Mean (best-known - best LB) / LB = {s2['bk_minus_lb_pct']:.3f}%.", "",
              "### Mean gap to best-known | gap to best lower bound (%)", "",
              "| n | scheme | budget | method | gap to BK | gap to LB |", "|---|---|---|---|---|---|"]
        cells = [k for k in s2 if k.startswith("n") and "@" in k]
        for k in cells:
            n, rest = k.split("_", 1)
            sc, b = rest.split("@")
            for m in LAB:
                if m in s2[k]:
                    L.append(f"| {n[1:]} | {sc} | {b} s | {LAB[m]} | {g(s2[k][m]['bk'])} | {g(s2[k][m]['lb'])} |")
        L += ["", "### Best method per cell (lowest mean gap to BK among methods with a set on every instance)", ""]
        for k in cells:
            if "_best" in s2[k]:
                L.append(f"- {k}: {LAB[s2[k]['_best']]}")
        L += ["", "### Guided restarts vs X (Wilcoxon p; W/T/L)", "", "| cell | X | p | W/T/L |", "|---|---|---|---|"]
        for k in cells:
            for c in ("plain", "lp_ls", "cpsat", "random_prior", "ours_bok_ls"):
                x = s2[k].get(f"guided_vs_{c}")
                if x:
                    L.append(f"| {k} | {LAB[c]} | {p(x['p'])} | {x['win']}/{x['tie']}/{x['loss']} |")
        L += ["", "### GNN timing (step 2)", ""]
        for n, x in s2["greedy_rollout_rr_time"].items():
            L.append(f"- n = {n}: one greedy rollout + RR {x['mean']:.3f} s mean, {x['max']:.3f} s max "
                     f"(device {s2['devices'].get(n, s2['devices'].get(int(n), '?'))})")
        for k, x in s2["first_solution_time"].items():
            L.append(f"- first solution {k}: mean {x['mean']:.3f} s, max {x['max']:.3f} s")
    if "device_bench" in r:
        L += ["", "## CPU vs GPU (one greedy rollout, seed-0 model, first ER degree graph per n)", ""]
        for n, x in r["device_bench"]["per_n"].items():
            L.append(f"- n = {n}: CPU {x['cpu']:.3f} s, GPU {x['cuda']:.3f} s -> {x['chosen']}")
        L.append("- n <= 200: CPU (measured in revision 1, results/revision/inference_*.json)")
    L += ["", "## Files", "",
          "- traces: results/revision2/step1_traces.csv, step2_traces.csv (scripts/rev2_run.py)",
          "- tables: results/revision2/tables/*.tex|csv; figures: results/revision2/figures/*.png|pdf "
          "(scripts/rev2_report.py)", "- tuning: results/revision2/tuning/ (scripts/rev2_tune.py)",
          "- step-2 graphs: data/rev2_large.npz|json; device choice: results/revision2/device_bench.json", ""]
    (R2 / "SUMMARY.md").write_text("\n".join(L), encoding="utf-8")
    print("wrote", R2 / "SUMMARY.md")


if __name__ == "__main__":
    main()
